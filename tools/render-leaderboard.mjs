#!/usr/bin/env node
/**
 * render-leaderboard.mjs — render docs/leaderboard.md from
 * data/launches/_index.json (featured top-20) + data/control/_index.json
 * (unfeatured baseline). Rerun after refreshing either corpus.
 *
 * Usage: node tools/render-leaderboard.mjs
 */

import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const featured = JSON.parse(readFileSync(join(ROOT, "data/launches/_index.json"), "utf8"));
const control = JSON.parse(readFileSync(join(ROOT, "data/control/_index.json"), "utf8"));

const fMin = Math.min(...featured.map((r) => r.votes ?? Infinity));
const fMax = Math.max(...featured.map((r) => r.votes ?? 0));
const cMax = Math.max(...control.map((r) => r.votes ?? 0));
const cMedian = [...control.map((r) => r.votes ?? 0)].sort((a, b) => a - b)[Math.floor(control.length / 2)];
const over100 = control.filter((r) => (r.votes ?? 0) > 100).length;

const dates = (list) => {
  const ds = list.map((r) => r.launch_date).filter(Boolean).sort();
  return ds.length ? `${ds[0]} → ${ds[ds.length - 1]}` : "?";
};

const row = (r, i) =>
  `| ${i + 1} | [${r.name}](https://www.producthunt.com/products/${r.slug}) | ${r.votes ?? "?"} | ${r.comments ?? "?"} | ${r.launch_date ?? "?"} (${r.day_of_week ?? "?"}) |`;

const md = `# PH launch leaderboard

Auto-generated by \`tools/render-leaderboard.mjs\`. Refresh the corpora
(\`collect-launches\`, \`collect-control\`), then rerun this script.

**The gap in one line:** featured top-20 floor is **${fMin}** votes; the best
unfeatured launch of the month reached **${cMax}**. Median unfeatured outcome:
**${cMedian} votes**; launches over 100 votes among unfeatured: **${over100}/${control.length}**.

## Top ${featured.length} featured (${dates(featured)})

| # | Launch | Votes | Comments | Date |
|---|---|---|---|---|
${featured.map(row).join("\n")}

## Top ${Math.min(30, control.length)} unfeatured (${dates(control)})

| # | Launch | Votes | Comments | Date |
|---|---|---|---|---|
${control.slice(0, 30).map(row).join("\n")}

*Full unfeatured set: \`data/control/\` (${control.length} launches).*
`;

writeFileSync(join(ROOT, "docs/leaderboard.md"), md);
console.log(`wrote docs/leaderboard.md — featured floor ${fMin}, unfeatured top ${cMax}, median ${cMedian}`);
